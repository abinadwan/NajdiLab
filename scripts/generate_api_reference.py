"""Generate the implemented route inventory from server AST; never imports the app."""
import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render():
    tree = ast.parse((ROOT / 'app/server.py').read_text(encoding='utf-8'))
    handler = next(node for node in tree.body if isinstance(node, ast.ClassDef) and node.name == 'NajdiLabHandler')
    rows = []
    for method in handler.body:
        if not isinstance(method, ast.FunctionDef) or not method.name.startswith('do_'):
            continue
        for branch in ast.walk(method):
            if not isinstance(branch, ast.If):
                continue
            routes = [node.value for node in ast.walk(branch.test) if isinstance(node, ast.Constant)
                      and isinstance(node.value, str) and node.value.startswith('/api/v1/')]
            if not routes:
                continue
            route = routes[0]
            direct = ast.Module(body=branch.body, type_ignores=[])
            calls = [node for node in ast.walk(direct) if isinstance(node, ast.Call)]
            fields = sorted({node.args[0].value for node in calls if isinstance(node.func, ast.Attribute)
                             and isinstance(node.func.value, ast.Name) and node.func.value.id in {'data','query'}
                             and node.func.attr == 'get' and node.args and isinstance(node.args[0], ast.Constant)})
            response = next((node.args[0] for node in calls if isinstance(node.func, ast.Attribute)
                             and node.func.attr == '_json' and node.args), None)
            keys = []
            if isinstance(response, ast.Dict):
                keys = [node.value for node in response.keys if isinstance(node, ast.Constant)]
            dispatch = sorted({node.func.id for node in calls if isinstance(node.func, ast.Name)
                               and node.func.id not in {'str','int','bool','len'}})
            wrapper = ', '.join(str(key) for key in keys) if keys else 'domain return object'
            if isinstance(response, ast.Dict) and any(key is None for key in response.keys):
                wrapper += ', plus expanded domain fields'
            rows.append((method.name[3:], route, fields, wrapper, dispatch, branch.lineno))
    text = '# Implemented route inventory\n\nGenerated by `python scripts/generate_api_reference.py` from app/server.py without importing it. Regex paths are literal implementation patterns; they are not example URLs. Only implemented dispatch branches appear. See [API reference](api-reference.md) for security, shapes, idempotency and synthetic examples. Direct fields below are those parsed at the HTTP layer, not an exhaustive domain schema; follow the named contract implementation for complete validation/defaults.\n\n'
    text += '| Method | Path / pattern | Direct query/body fields | Success wrapper | Domain contract / handler |\n|---|---|---|---|---|\n'
    for method, route, fields, wrapper, dispatch, line in rows:
        route = route.replace('|', '&#124;')
        text += '| '+method+' | `'+route+'` | '+(', '.join(fields) or 'domain payload / none')+' | '+wrapper+' | '+', '.join(dispatch)+'; [source](../app/server.py#L'+str(line)+') |\n'
    text += '\nTotal implemented route branches: '+str(len(rows))+'. Response status and field details are defined at the linked handler/domain code; all mutations retain the documented request security and dataset integrity gates. No catch-all static route is an API operation.\n'
    return text


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'docs/api-routes.md'
    expected = render()
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != expected:
            raise SystemExit('API inventory is stale; run python scripts/generate_api_reference.py and review the diff.')
        print('PASS: implemented API route inventory matches source.')
    else:
        target.write_text(expected, encoding='utf-8', newline='\n')
        print('Generated docs/api-routes.md')
