def _create(ws, runtime, budget=2048, reserve=16):
    return ws.create({'provider': 'native', 'model': 'synthetic.gguf', 'selection_revision': runtime.revision,
                      'context_budget': budget, 'reply_reserve': reserve, 'load_approved': False})


def _send(ws, runtime, session, events=None):
    return ws.send(session['id'], {'request_id': str(uuid4()), 'revision': session['revision'],
                                   'selection_revision': runtime.revision, 'text': 'abc'},
                   on_event=events.append if events is not None else None)


@real
def test_real_native_lifecycle_streaming_admission_and_identity(native):
    runtime, ws, db, models = native
    status = runtime.start({'approved': True, 'model': 'synthetic.gguf', 'context_budget': 2048, 'gpu_layers': '0'})
    assert status['state'] == 'RUNNING' and status['context'] == 2048 and len(status['sha256']) == 64
    session = _create(ws, runtime)
    assert session['model_fingerprint'] == 'native:' + status['sha256']
    events = []
    # The synthetic model has no EOS row it can reach reliably, so a reply may end
    # at the reserve: that is a correct refusal (STOP_REASON_LENGTH), never a save.
    try:
        result = _send(ws, runtime, session, events)
        saved = result['session']['turns'][0]
        assert saved['assistant'] == ''.join(e['text'] for e in events if e['type'] == 'content')
        assert saved['input_tokens'] == next(e['input_tokens'] for e in events if e['type'] == 'admitted')
    except IntegrationError as error:
        assert error.code == 'INCOMPLETE_RESPONSE' and error.check == 'STOP_REASON_LENGTH'
        with connect(db) as conn:
            assert conn.execute('SELECT COUNT(*) FROM chat_turns').fetchone()[0] == 0
    assert any(e['type'] == 'content' for e in events), 'tokens streamed before the final check'
    # Loopback only, and an API key is required even there.
    run = runtime._run
    with pytest.raises(IntegrationError) as auth:
        request_json(run['connector'], '/props', timeout=3)
    assert auth.value.code == 'AUTH_REQUIRED'
    external = socket.gethostbyname(socket.gethostname())
    if not external.startswith('127.'):
        with pytest.raises(OSError):
            socket.create_connection((external, run['connector'].port), timeout=2).close()
    with pytest.raises(IntegrationError) as busy:
        runtime.start({'approved': True, 'model': 'synthetic.gguf', 'context_budget': 2048, 'gpu_layers': '0'})
    assert busy.value.code == 'NATIVE_RUNNING'


@real
def test_real_native_refuses_wrong_context_changed_file_and_stopped_runtime(native):
    runtime, ws, db, models = native
    runtime.start({'approved': True, 'model': 'synthetic.gguf', 'context_budget': 2048, 'gpu_layers': '0'})
    with pytest.raises(IntegrationError) as limit:
        _create(ws, runtime, budget=4096)
    assert limit.value.code == 'ENGINE_CONTEXT_LIMIT'
    session = _create(ws, runtime)
    path = models / 'synthetic.gguf'
    stat = path.stat()
    os.utime(path, ns=(stat.st_atime_ns, stat.st_mtime_ns + 10 ** 9))
    with pytest.raises(IntegrationError) as changed:
        _send(ws, runtime, session)
    assert changed.value.code == 'MODEL_CHANGED'
    runtime.stop({'approved': True})
    with pytest.raises(IntegrationError) as stopped:
        _send(ws, runtime, ws.get(session['id']))
    assert stopped.value.code in {'NOT_CONNECTED', 'STALE_SELECTION'}
    with connect(db) as conn:
        assert conn.execute('SELECT COUNT(*) FROM chat_turns').fetchone()[0] == 0


@real
def test_real_native_stop_during_generation_saves_nothing(native):
    runtime, ws, db, models = native
    runtime.start({'approved': True, 'model': 'synthetic.gguf', 'context_budget': 2048, 'gpu_layers': '0'})
    session = _create(ws, runtime, reserve=1500)
    events = []

    def watch(event):
        events.append(event)
        if event['type'] == 'content' and len(events) > 5:
            ws.stop(session['id'])
    with pytest.raises(IntegrationError) as error:
        ws.send(session['id'], {'request_id': str(uuid4()), 'revision': session['revision'],
                                'selection_revision': runtime.revision, 'text': 'abc'}, on_event=watch)
    assert error.value.code == 'STOPPED'
    with connect(db) as conn:
        assert conn.execute('SELECT COUNT(*) FROM chat_turns').fetchone()[0] == 0
        assert conn.execute('SELECT status FROM chat_requests').fetchone()[0] == 'STOPPED'
    assert runtime.status()['state'] == 'RUNNING', 'stopping a reply never stops the runtime'


