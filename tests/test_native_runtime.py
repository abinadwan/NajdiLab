def test_gguf_header_is_read_without_tensors(models):
    info = describe(read_header(models / 'synthetic.gguf'))
    assert info['architecture'] == 'llama' and info['model_max_context'] == 8192 and info['quantization'] == 'F32'
    assert info['kv']['block_count'] == 1 and info['chat_template'] is False


@pytest.mark.parametrize('mutate,code', [
    (lambda b: b'GGML' + b[4:], 'NOT_GGUF'),
    (lambda b: b[:4] + struct.pack('<I', 9) + b[8:], 'UNSUPPORTED_VERSION'),
    (lambda b: b[:200], 'TRUNCATED'),
    (lambda b: b[:8] + struct.pack('<QQ', 0, 10 ** 9) + b[24:], 'HEADER_LIMITS'),
    (lambda b: b[:10], 'TOO_SMALL'),
])
def test_gguf_rejects_damaged_or_hostile_headers(models, tmp_path, mutate, code):
    bad = tmp_path / 'bad.gguf'
    bad.write_bytes(mutate((models / 'synthetic.gguf').read_bytes()))
    with pytest.raises(GGUFError) as error:
        read_header(bad)
    assert error.value.code == code


def test_discovery_lists_invalid_files_and_never_leaves_the_folder(models, tmp_path):
    (models / 'notes.gguf').write_bytes(b'not a model at all, just text....')
    (models / 'big-00001-of-00002.gguf').write_bytes(b'x' * 64)
    runtime = NativeRuntime(tmp_path / 'missing-server', models)
    items = {i['id']: i for i in runtime.models()['items']}
    assert items['synthetic.gguf']['valid'] is True
    assert items['notes.gguf']['error'] == 'NOT_GGUF'
    assert items['big-00001-of-00002.gguf']['error'] == 'SPLIT_UNSUPPORTED'
    outside = tmp_path / 'outside.gguf'
    write_gguf(outside)
    for model in ('../outside.gguf', str(outside), 'synthetic.gguf/../../outside.gguf', '..\\outside.gguf', ''):
        with pytest.raises(IntegrationError) as error:
            runtime.model_limits(model)
        assert error.value.code in {'NATIVE_MODEL_INVALID', 'NATIVE_MODEL_NOT_FOUND'}
    assert runtime.models()['downloads'] == 'NEVER'


def test_start_requires_approval_valid_options_and_an_existing_binary(models, tmp_path):
    runtime = NativeRuntime(tmp_path / 'missing-server', models)
    good = {'approved': True, 'model': 'synthetic.gguf', 'context_budget': 2048, 'gpu_layers': '0'}
    for bad in ({**good, 'approved': False}, {k: v for k, v in good.items() if k != 'approved'}, {**good, 'extra': 1}):
        with pytest.raises(IntegrationError) as error:
            runtime.start(bad)
        assert error.value.code == 'APPROVAL_REQUIRED'
    for bad in ({**good, 'gpu_layers': '0; rm -rf /'}, {**good, 'gpu_layers': 5}, {**good, 'context_budget': 100}):
        with pytest.raises(IntegrationError):
            runtime.start(bad)
    with pytest.raises(IntegrationError) as missing:
        runtime.start(good)
    assert missing.value.code == 'NATIVE_SERVER_MISSING'
    assert runtime.status()['state'] == 'STOPPED'
    with pytest.raises(IntegrationError) as lease:
        with runtime.chat_lease('synthetic.gguf', runtime.revision):
            pass
    assert lease.value.code == 'NOT_CONNECTED'


